def glyph_bits(ch):
    rows = F.get(ch)
    if rows is None:
        rows = F.get('?')
    out = []
    for r in rows:
        b = 0
        for c in r:
            b = (b << 1) | (1 if c == '#' else 0)
        out.append(b)
    return out

def main():
    lines = []
    lines.append("/* 8x16 bitmap font for SlopOS. Generated by tools/genfont16.py. 0BSD. */")
    lines.append("#include \"font8x16.h\"")
    lines.append("")
    lines.append("/* Indexed by ASCII code (32..126). 16 bytes per glyph. */")
    lines.append("const u8 font8x16[95][16] = {")
    for code in range(0x20, 0x7F):
        ch = chr(code)
        g = glyph_bits(ch)
        vals = ", ".join("0x%02X" % v for v in g)
        lines.append("    { %s },   /* %s */" % (vals, repr(ch)))
    lines.append("};")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(lines) + "\n")
    print("generated %d 8x16 glyphs" % (0x7F - 0x20))

if __name__ == "__main__":
    main()
